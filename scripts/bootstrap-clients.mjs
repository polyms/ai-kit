import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  readlinkSync,
  renameSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs'
import { homedir } from 'node:os'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse, stringify } from 'yaml'

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const skills = join(homedir(), '.agents', 'skills')
const target = process.argv[2] || 'codex'
if (!['all', 'codex', 'copilot'].includes(target)) {
  throw new Error('Usage: node scripts/bootstrap-clients.mjs [all|codex|copilot]')
}
const clients = target === 'all' ? ['codex', 'copilot'] : [target]

// Keep every replaced entry, including broken symlinks and earlier backups.
function backup(target) {
  if (!existsSync(target) && !lstatSync(target, { throwIfNoEntry: false })) return
  // Backups must stay outside discovery folders, or Codex also loads old skills.
  const backupDirectory = join(dirname(dirname(target)), 'ai-kit-backups', basename(dirname(target)))
  mkdirSync(backupDirectory, { recursive: true })
  const base = join(backupDirectory, `${basename(target)}.bak`)
  let destination = base
  for (let index = 1; lstatSync(destination, { throwIfNoEntry: false }); index++) {
    destination = `${base}.${index}`
  }
  renameSync(target, destination)
  console.log(`Backup: ${target} -> ${destination}`)
}

// Validate all role definitions before changing the installation.
const roles = readdirSync(join(repo, 'agents'))
  .filter(name => name.endsWith('.md'))
  .map(file => {
    const source = join(repo, 'agents', file)
    const content = readFileSync(source, 'utf8')
    const frontmatter = content.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)
    if (!frontmatter) throw new Error(`Missing agent frontmatter: ${source}`)
    const role = parse(frontmatter[1])
    if (
      typeof role.name !== 'string' ||
      !/^[a-z][a-z0-9_-]*$/.test(role.name) ||
      role.name !== file.slice(0, -3) ||
      typeof role.description !== 'string' ||
      !role.description.trim()
    ) {
      throw new Error(`Invalid agent name or description: ${source}`)
    }
    const instructions =
      `Read ${JSON.stringify(join(repo, 'docs/agents/client-compatibility.md'))} for the current client before following the role.\n` +
      `Read and follow the principal role instructions at ${JSON.stringify(source)} before starting work.\n` +
      `Resolve references to ~/.cursor/skills/ and kit playbooks under skills/ through ${JSON.stringify(join(repo, 'skills'))}. ` +
      `Resolve references to kit agents/ and docs/agents/invocation.md through ${JSON.stringify(repo)}. ` +
      'Other project context, ADRs, design specs, and documentation belong to the active project.\n' +
      'Use the skills and subagent tools available in this session. Follow the parent task scope and communication preferences.\n'
    const toml =
      '# Generated by ai-kit bootstrap; edit agents/*.md and rerun bootstrap for metadata changes.\n' +
      `name = ${JSON.stringify(role.name)}\n` +
      `description = ${JSON.stringify(role.description)}\n` +
      `developer_instructions = ${JSON.stringify(instructions)}\n`
    const copilot = `---\n${stringify({ name: role.name, description: role.description })}---\n\n${instructions}`
    return { name: role.name, toml, copilot }
  })

mkdirSync(skills, { recursive: true })

for (const entry of readdirSync(join(repo, 'skills'), { withFileTypes: true })) {
  const source = join(repo, 'skills', entry.name)
  if (!entry.isDirectory() || !existsSync(join(source, 'SKILL.md'))) continue
  const target = join(skills, entry.name)
  const current = lstatSync(target, { throwIfNoEntry: false })
  if (current?.isSymbolicLink() && resolve(dirname(target), readlinkSync(target)) === source) continue
  backup(target)
  symlinkSync(source, target, 'dir')
  console.log(`Linked: ${target} -> ${source}`)
}

for (const client of clients) {
  const agents = join(
    client === 'codex' ? process.env.CODEX_HOME || join(homedir(), '.codex') : join(homedir(), '.copilot'),
    'agents'
  )
  mkdirSync(agents, { recursive: true })
  for (const role of roles) {
    const content = client === 'codex' ? role.toml : role.copilot
    const target = join(agents, `${role.name}.${client === 'codex' ? 'toml' : 'agent.md'}`)
    const current = lstatSync(target, { throwIfNoEntry: false })
    if (current?.isFile() && readFileSync(target, 'utf8') === content) continue
    backup(target)
    writeFileSync(target, content, { flag: 'wx' })
    console.log(`Installed: ${target}`)
  }
}
